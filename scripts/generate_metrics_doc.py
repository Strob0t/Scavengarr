"""Generate the metric table of docs/reference/metrics.md from the app's registry.

Usage:
    PYTHONPATH=src poetry run python scripts/generate_metrics_doc.py
    PYTHONPATH=src poetry run python scripts/generate_metrics_doc.py --check

The first rewrites the table, the second exits 1 when it is outdated.

The table lists every ``scavengarr_*`` family ``GET /metrics`` serves: the
ones ``Telemetry`` registers (each stage's duration and outcome counter, the
values, the event-loop lag, the build) and the ones read at scrape time
(``collectors.py``: breakers, browser pages, the container's cgroup), with its
type, labels, histogram buckets and help text, generated between the markers
``<!-- metrics:start -->`` and ``<!-- metrics:end -->``. prometheus-client's
own ``process_*`` and ``python_*`` families stay out.
``tests/unit/infrastructure/test_metrics_doc.py`` fails when the doc differs
from the output of :func:`update`.
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

from prometheus_client.metrics import MetricWrapperBase
from prometheus_client.metrics_core import Metric

from scavengarr.infrastructure.browser.page_gate import PageGate
from scavengarr.infrastructure.telemetry.collectors import (
    BreakerCollector,
    BrowserPagesCollector,
    ContainerCollector,
)
from scavengarr.infrastructure.telemetry.metrics import Telemetry

_ROOT = Path(__file__).resolve().parents[1]
_DOC = _ROOT / "docs" / "reference" / "metrics.md"
_START = "<!-- metrics:start -->"
_END = "<!-- metrics:end -->"
# The exposed sample name per type: a counter's ``_total``, an info's ``_info``
_SUFFIX = {"counter": "_total", "info": "_info"}


def _row(name: str, kind: str, labels: tuple[str, ...], buckets: str, text: str) -> str:
    labelled = ", ".join(f"`{label}`" for label in labels)
    return f"| {' | '.join((f'`{name}`', kind, labelled, buckets, text))} |"


def _wrapper_row(metric: MetricWrapperBase) -> tuple[str, str]:
    kind = metric._type
    name = metric._name + _SUFFIX.get(kind, "")
    labels = metric._labelnames
    if kind == "info":
        # An info's labels are its values: the one sample names them
        family = next(iter(metric.collect()))
        labels = tuple(family.samples[0].labels)
    buckets = ""
    if kind == "histogram":
        bounds: list[float] = getattr(metric, "_upper_bounds")
        buckets = ", ".join(f"{bound:g}" for bound in bounds[:-1])
    return name, _row(name, kind, labels, buckets, metric._documentation)


def _family_row(family: Metric) -> tuple[str, str]:
    name = family.name + _SUFFIX.get(family.type, "")
    labels: tuple[str, ...] = getattr(family, "_labelnames", ())
    return name, _row(name, family.type, labels, "", family.documentation)


def _scrape_time_families() -> list[Metric]:
    """The families of ``collectors.py``, collected from stand-ins."""
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        (root / "app").mkdir()
        (root / "app" / "cpu.stat").write_text("usage_usec 1\n")
        (root / "app" / "memory.current").write_text("1\n")
        (root / "cgroup").write_text("0::/app\n")
        container = ContainerCollector(root=root, proc_cgroup=root / "cgroup")
        return [
            *BreakerCollector({}).collect(),
            *BrowserPagesCollector(PageGate(limit=1)).collect(),
            *container.collect(),
        ]


def render() -> str:
    """The metric table, one row per family, sorted by name."""
    registry = Telemetry().registry
    rows = dict(
        _wrapper_row(collector)
        for collector in registry._collector_to_names
        if isinstance(collector, MetricWrapperBase)
    )
    rows.update(_family_row(family) for family in _scrape_time_families())
    header = [
        "| Metric | Type | Labels | Buckets | Help |",
        "|---|---|---|---|---|",
    ]
    return "\n".join([*header, *(rows[name] for name in sorted(rows))])


def update(doc: str) -> str:
    """*doc* with the block between the markers replaced by :func:`render`."""
    before, rest = doc.split(_START, 1)
    _, after = rest.split(_END, 1)
    note = "<!-- Generated by scripts/generate_metrics_doc.py, do not edit by hand. -->"
    return f"{before}{_START}\n{note}\n\n{render()}\n{_END}{after}"


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if the table is outdated"
    )
    args = parser.parse_args()

    current = _DOC.read_text(encoding="utf-8")
    text = update(current)
    if args.check:
        if current != text:
            print(f"{_DOC.relative_to(_ROOT)} is outdated", file=sys.stderr)
            return 1
        return 0
    _DOC.write_text(text, encoding="utf-8")
    print(f"wrote {_DOC.relative_to(_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
