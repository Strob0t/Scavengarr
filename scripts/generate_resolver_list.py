"""Generate docs/reference/resolvers.md from the hoster resolver registrations.

Usage:
    PYTHONPATH=src poetry run python scripts/generate_resolver_list.py
    PYTHONPATH=src poetry run python scripts/generate_resolver_list.py --check

The first rewrites the file, the second exits 1 when it is outdated.

The list is generated, not written by hand, so it cannot drift from the
registrations: ``build_hoster_resolvers()`` of the composition root, whose
generic resolvers come from ``ALL_DDL_CONFIGS`` and ``ALL_XFS_CONFIGS``.
``tests/unit/infrastructure/test_resolver_list_doc.py`` fails when
``docs/reference/resolvers.md`` differs from the output of :func:`render`.
"""

from __future__ import annotations

import argparse
import asyncio
import inspect
import re
import sys
from pathlib import Path

import httpx

from scavengarr.domain.ports.hoster_resolver import (
    ClientBoundResolverPort,
    HosterResolverPort,
)
from scavengarr.infrastructure.hoster_resolvers.generic_ddl import (
    ALL_DDL_CONFIGS,
    GenericDDLResolver,
)
from scavengarr.infrastructure.hoster_resolvers.xfs import ALL_XFS_CONFIGS, XFSResolver
from scavengarr.interfaces.composition import build_hoster_resolvers

_ROOT = Path(__file__).resolve().parents[1]
_OUT = _ROOT / "docs" / "reference" / "resolvers.md"
_SOURCE = "../../src/scavengarr/infrastructure/hoster_resolvers"

# One sentence per line, as the docs' contract asks
_HEADER = "\n".join(
    (
        "# Hoster resolvers",
        "",
        "> Generated by `scripts/generate_resolver_list.py` from the resolver"
        " registrations, do not edit by hand.",
        "",
        "Every resolver below is registered by `build_hoster_resolvers()` in"
        " `src/scavengarr/interfaces/composition.py`.",
        "How the registry dispatches a link to a resolver and judges its answer:"
        " [Hoster resolvers](../current/hoster-resolvers.md).",
        "*What it does* is the first sentence of the resolver module's docstring,"
        " which describes the technique in full.",
        "*Capture* marks a resolver that can take the stream from the stealth browser.",
        "*Bound* names what the CDN binds a video URL to: `address` sends the file"
        " through the file proxy, header names make `/play` resolve the link per"
        " player.",
        "*Check* marks a resolver whose streams the playback check reads with"
        " `stremio.verify_streams` off too.",
        "",
    )
)


def registrations() -> list[HosterResolverPort]:
    """The resolvers the app registers, built with a client that sends nothing."""
    client = httpx.AsyncClient()
    try:
        return build_hoster_resolvers(client, None)
    finally:
        asyncio.run(client.aclose())


def _generic(resolver: HosterResolverPort) -> bool:
    return isinstance(resolver, XFSResolver | GenericDDLResolver)


def _summary(resolver: HosterResolverPort) -> str:
    """The first sentence of the module docstring, after the hoster's name."""
    doc = sys.modules[type(resolver).__module__].__doc__ or ""
    first = " ".join(doc.strip().split("\n\n")[0].split()).replace("``", "`")
    first = first.split(" — ", 1)[-1]
    first = re.split(r"(?<=\.)\s", first, maxsplit=1)[0]
    first = first[:1].upper() + first[1:]
    return first if first.endswith(".") else f"{first}."


def _module(resolver: HosterResolverPort) -> str:
    name = type(resolver).__module__.rsplit(".", 1)[1]
    return f"[`{name}.py`]({_SOURCE}/{name}.py)"


def _capture(resolver: HosterResolverPort) -> str:
    params = inspect.signature(type(resolver).__init__).parameters
    return "yes" if "stealth_pool" in params else ""


def _bound(resolver: HosterResolverPort) -> str:
    if isinstance(resolver, ClientBoundResolverPort):
        return ", ".join(f"`{name}`" for name in resolver.bound_headers)
    return "`address`" if getattr(resolver, "address_bound", False) else ""


def _check(resolver: HosterResolverPort) -> str:
    return "yes" if getattr(resolver, "needs_playback_check", False) else ""


def _domains(resolver: HosterResolverPort) -> str:
    names = {resolver.name, *getattr(resolver, "supported_domains", ())}
    line = f"- `{resolver.name}`: " + ", ".join(f"`{d}`" for d in sorted(names))
    hosts = sorted(getattr(resolver, "supported_hosts", ()))
    if hosts:
        line += "; hosts " + ", ".join(f"`{h}`" for h in hosts)
    return line


def _xfs_kind(name: str) -> str:
    config = next(c for c in ALL_XFS_CONFIGS if c.name == name)
    if config.needs_captcha:
        return "captcha, no stream"
    return "video" if config.is_video_hoster else "file check"


def render() -> str:
    """Return the complete Markdown for ``docs/reference/resolvers.md``."""
    resolvers = sorted(registrations(), key=lambda r: r.name)
    individual = [r for r in resolvers if not _generic(r)]
    ddl = sorted(ALL_DDL_CONFIGS, key=lambda c: c.name)
    xfs = sorted(ALL_XFS_CONFIGS, key=lambda c: c.name)
    lines = [
        _HEADER.rstrip("\n"),
        "",
        f"{len(resolvers)} resolvers: {len(individual)} individual ones,"
        f" {len(ddl)} generic DDL hosters and {len(xfs)} XFS hosters.",
        "",
        "## Individual resolvers",
        "",
        "| Resolver | Module | What it does | Capture | Bound | Check |",
        "|---|---|---|---|---|---|",
    ]
    lines += [
        f"| `{r.name}` | {_module(r)} | {_summary(r)} | {_capture(r)}"
        f" | {_bound(r)} | {_check(r)} |"
        for r in individual
    ]
    lines += [
        "",
        "## Generic DDL hosters",
        "",
        "`GenericDDLResolver` in `generic_ddl.py` checks the file page of each"
        " hoster below, one `GenericDDLConfig` in `ALL_DDL_CONFIGS` per hoster.",
        "",
        "| Hoster | File id from | Shortest id |",
        "|---|---|---|",
    ]
    lines += [
        f"| `{c.name}` | {c.file_id_source} | {c.min_file_id_len or 'any'} |"
        for c in ddl
    ]
    lines += [
        "",
        "## XFS hosters",
        "",
        "`XFSResolver` in `xfs.py` handles each XFileSharingPro hoster below, one"
        " `XFSConfig` in `ALL_XFS_CONFIGS` per hoster.",
        "A video hoster's embed page behind a Cloudflare challenge, or with a captcha"
        " play button instead of a video, is captured in the stealth browser.",
        "",
        "| Hoster | Kind |",
        "|---|---|",
    ]
    lines += [f"| `{c.name}` | {_xfs_kind(c.name)} |" for c in xfs]
    lines += [
        "",
        "## Domains",
        "",
        "The second-level names each resolver takes, its name included, and the"
        " full host names it claims before them.",
        "",
    ]
    lines += [_domains(r) for r in resolvers]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if docs/reference/resolvers.md is outdated",
    )
    args = parser.parse_args()

    text = render()
    if args.check:
        current = _OUT.read_text(encoding="utf-8") if _OUT.exists() else ""
        if current != text:
            print("docs/reference/resolvers.md is outdated", file=sys.stderr)
            return 1
        return 0
    _OUT.write_text(text, encoding="utf-8")
    print(f"wrote {_OUT.relative_to(_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
